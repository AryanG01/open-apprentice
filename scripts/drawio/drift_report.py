"""Font drift report (spec 6), authoring Mac only: measure each dev-corpus label under the draw.io CLI export with the host's
real Helvetica, and under the engine profile (bundled Liberation Sans as Helvetica), and report the largest box difference.

The CLI export translates the drawing, so a per-page translation is removed first: the median difference of label CENTRES
(single-line labels keep their centre when only glyph widths change for centre-aligned text; for left/right-aligned text the
translation is still dominated by the many centre-aligned labels). The residual edge differences are the reported drift.

Usage: OA engine running at ENGINE_URL (default http://127.0.0.1:8090);  python scripts/drawio/drift_report.py
Writes docs/corpus/drift_report.md. Needs the `drawio` CLI (draw.io desktop) on PATH."""

from __future__ import annotations

import json
import os
import shutil
import statistics
import subprocess
import sys
import tempfile
from pathlib import Path

from open_apprentice.drawio.classify import classify
from open_apprentice.drawio.parse import load_drawio
from open_apprentice.drawio.render import render_page

CORPUS = Path("tests/fixtures/drawio_corpus/dev")
OUT = Path("docs/corpus/drift_report.md")


def cli_boxes(file: Path, page_index: int, tmp: Path) -> dict[str, dict[str, float]]:
    svg = tmp / f"{file.stem}-{page_index}.svg"
    subprocess.run(
        [
            "drawio",
            "-x",
            "-f",
            "svg",
            "--embed-svg-fonts",
            "false",
            "-p",
            str(page_index + 1),  # the CLI numbers pages from 1
            "-o",
            str(svg),
            str(file),
        ],
        check=True,
        capture_output=True,
    )
    out = subprocess.run(
        ["node", "scripts/drawio/drift_measure.mjs", str(svg)],
        check=True,
        capture_output=True,
        text=True,
    )
    return json.loads(out.stdout)


def main() -> None:
    if shutil.which("drawio") is None:
        sys.exit(
            "the draw.io CLI (`drawio`) is not on PATH; the drift report is produced on the authoring Mac only"
        )
    engine = os.environ.get("ENGINE_URL", "http://127.0.0.1:8090")
    rows, profile = [], {}
    with tempfile.TemporaryDirectory() as t:
        for file in sorted(CORPUS.glob("*.drawio")):
            f = load_drawio(file.read_bytes())
            for page in f.pages:
                c = classify(page)
                r = render_page(page, engine, png=False)
                profile = r.profile
                text = {cell.id: cell.value.strip() for cell in page.cells}
                theirs = cli_boxes(file, page.index, Path(t))
                pairs = [
                    (r.labels[cid][0], theirs[text[cid]])
                    for cid in c.movable
                    if cid in r.labels and text.get(cid) in theirs
                ]
                if not pairs:
                    rows.append((file.name, page.index, 0, None))
                    continue
                tx = statistics.median(
                    (b["x"] + b["w"] / 2) - float(a.x + a.w / 2) for a, b in pairs
                )
                ty = statistics.median(
                    (b["y"] + b["h"] / 2) - float(a.y + a.h / 2) for a, b in pairs
                )
                worst = max(
                    max(
                        abs(b["x"] - tx - float(a.x)),
                        abs(b["y"] - ty - float(a.y)),
                        abs(b["x"] + b["w"] - tx - float(a.x + a.w)),
                        abs(b["y"] + b["h"] - ty - float(a.y + a.h)),
                    )
                    for a, b in pairs
                )
                rows.append((file.name, page.index, len(pairs), worst))
    lines = [
        "# Font drift report (draw.io CLI, real Helvetica) vs engine profile",
        "",
        "Generated by `scripts/drawio/drift_report.py` on the authoring Mac. Engine profile: viewer "
        f"`{profile.get('viewer_sha256', '?')[:12]}…`, font {profile.get('font', '?')} "
        f"(Regular `{profile.get('font_sha256', {}).get('Regular', '?')[:12]}…`), Chromium {profile.get('chromium', '?')}.",
        "",
        "| file | page | labels matched | max box difference (document units) |",
        "|---|---|---|---|",
    ]
    lines += [f"| {n} | {p} | {k} | {'n/a' if w is None else f'{w:.2f}'} |" for n, p, k, w in rows]
    worst_all = max((w for *_, w in rows if w is not None), default=None)
    lines += [
        "",
        f"Receipts for these files may say: other font environments may differ by up to "
        f"{'n/a' if worst_all is None else f'{worst_all:.2f}'} units (measured). For uploads in the deployed service the "
        "drift is not measured.",
        "",
        "A difference near zero is expected rather than suspicious: Liberation Sans is metric-compatible with "
        "Arial/Helvetica (same advance widths), so single-line label boxes match; the export measured here requests "
        "`font-family: Helvetica` and renders with the host's real Helvetica.",
    ]
    OUT.write_text("\n".join(lines) + "\n")
    print(OUT.read_text())


if __name__ == "__main__":
    main()
